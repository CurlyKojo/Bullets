// "*word*" marks the accent word. Every word is its own span so it can land on its own.
function words(text, cls, accent) {
  const out = [];
  let hot = false;
  for (const tok of text.split(/(\*)/)) {
    if (tok === "*") { hot = !hot; continue; }
    for (const w of tok.split(/\s+/).filter(Boolean)) {
      out.push(`<span class="${cls}"${hot ? ` style="color:${accent}"` : ""}>${w}</span>`);
    }
  }
  return out.join(" ");
}

// ---- Transitions, written into each scene's own timeline --------------------------------
function enterJs(s, P) {
  const t = s.cutIn;
  switch (s.inSeam) {
    case "whip":
      return `tl.fromTo("#${P}-cam", { x: 1080, filter: "blur(14px)" }, { x: 0, filter: "blur(0px)", duration: ${r3(2 * H)}, ease: "power3.out" }, 0);`;
    case "blurswap":
      return `tl.fromTo("#${P}-cam", { opacity: 0, filter: "blur(10px)" }, { opacity: 1, filter: "blur(0px)", duration: ${r3(2 * H)}, ease: "power2.out" }, 0);`;
    case "zoomthrough":
      return `tl.fromTo("#${P}-cam", { opacity: 0, scale: 1.18, filter: "blur(10px)" }, { opacity: 1, scale: 1, filter: "blur(0px)", duration: 0.4, ease: "expo.out" }, 0.05);`;
    case "iris":
      return `tl.fromTo("#${P}-cam", { clipPath: "circle(0% at 424px 828px)" }, { clipPath: "circle(130% at 424px 828px)", duration: 0.42, ease: "power3.inOut" }, 0);`;
    case "dip":
      return `tl.fromTo("#${P}-cam", { opacity: 0 }, { opacity: 1, duration: ${r3(2 * H)}, ease: "power2.out" }, 0);`;
    default:
      return `// enters on a hard cut under the light leak (t=${t})`;
  }
}
function exitJs(s, P) {
  const t0 = r3(s.cutOut - H);
  switch (s.outSeam) {
    case "whip":
      return `tl.to("#${P}-cam", { x: -1080, filter: "blur(14px)", duration: ${r3(2 * H)}, ease: "power3.in" }, ${t0});`;
    case "blurswap":
      return `tl.to("#${P}-media, #${P}-copy", { opacity: 0, filter: "blur(10px)", duration: 0.2, ease: "power2.in" }, ${r3(t0 + 0.05)});`;
    case "zoomthrough":
      return `tl.to("#${P}-cam", { scale: 1.5, opacity: 0, filter: "blur(12px)", duration: ${r3(2 * H)}, ease: "power3.in" }, ${t0});`;
    case "iris":
      // Punch toward the Ghost's eye; the next scene opens out of it.
      return `tl.to("#${P}-cam", { scale: 1.35, duration: 0.45, ease: "power2.in" }, ${r3(s.cutOut - 0.45)});`;
    case "dip":
      return `tl.to("#${P}-cam", { opacity: 0, filter: "blur(8px)", duration: ${r3(2 * H)}, ease: "power2.in" }, ${t0});`;
    default:
      return "";
  }
}

// Words land like speech: whole words, settling from 1.35x, never growing from zero.
function wordsJs(sel, at, gap) {
  return `tl.fromTo("${sel}", { opacity: 0, scale: 1.35, filter: "blur(6px)" }, { opacity: 1, scale: 1, filter: "blur(0px)", duration: 0.34, ease: "expo.out", stagger: ${gap} }, ${r3(at)});`;
}
function captionJs(sel, at) {
  return `tl.fromTo("${sel}", { opacity: 0, filter: "blur(8px)" }, { opacity: 1, filter: "blur(0px)", duration: 0.2, ease: "power2.out" }, ${r3(at)});`;
}

